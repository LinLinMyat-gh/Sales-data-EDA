-- 6. Ranking Analysis
-- Which 5 products generate the highest revenue?
SELECT p.product_name,
	SUM(s.sales_amount) AS total_revenue
FROM dim_products AS p
LEFT JOIN fact_sales AS s
ON p.product_key = s.product_key
GROUP BY 1
ORDER BY 2 DESC
LIMIT 5;

SELECT p.product_name,
	SUM(s.sales_amount) AS total_revenue,
    ROW_NUMBER() OVER(ORDER BY SUM(s.sales_amount) DESC) as rank_products
FROM dim_products AS p
LEFT JOIN fact_sales AS s
ON p.product_key = s.product_key
GROUP BY 1
LIMIT 5;

WITH RankedProducts AS (
SELECT p.product_name,
	SUM(s.sales_amount) AS total_revenue,
    ROW_NUMBER() OVER(ORDER BY SUM(s.sales_amount) DESC) as rank_products
FROM dim_products AS p
LEFT JOIN fact_sales AS s
ON p.product_key = s.product_key
GROUP BY 1)
SELECT *
FROM RankedProducts
WHERE rank_products <= 5;


-- Which 5 subcategories generate the highest revenue?
SELECT p.subcategory,
	SUM(s.sales_amount) AS total_revenue
FROM dim_products AS p
LEFT JOIN fact_sales AS s
ON p.product_key = s.product_key
GROUP BY 1
ORDER BY 2 DESC
LIMIT 5;

-- What are the 5 worst performing products in term of sales?
SELECT p.product_name,
	SUM(s.sales_amount) AS total_revenue
FROM dim_products AS p
LEFT JOIN fact_sales AS s
ON p.product_key = s.product_key
WHERE s.sales_amount IS NOT NULL
GROUP BY 1
ORDER BY 2 
LIMIT 5;

-- Finding the top 10 customers who generated the highest revenue
SELECT *
FROM (
SELECT c.customer_key, 
	c.first_name, 
    c.last_name, 
    SUM(s.sales_amount), 
    DENSE_RANK() OVER(ORDER BY SUM(s.sales_amount) DESC) AS rank_customers
FROM dim_customers AS c
LEFT JOIN fact_sales AS s
ON c.customer_key = s.customer_key
GROUP BY 1,2,3) AS RankedCustomers
WHERE rank_customers <= 10;

-- The 3 customers with the fewest orders placed
WITH RankedOrders AS (
SELECT c.customer_key, 
	c.first_name, 
    c.last_name,
    COUNT(distinct s.order_number) AS total_orders,
    DENSE_RANK() OVER (ORDER BY COUNT(distinct s.order_number)) AS rank_orders
FROM dim_customers AS c
INNER JOIN fact_sales AS s
ON c.customer_key = s.customer_key
GROUP BY 1,2,3) 
SELECT *
FROM RankedOrders
limit 3;












