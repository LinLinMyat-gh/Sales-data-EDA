-- 3. Date Exploration
-- Finding the date of first and last order
-- Finding the years of sales
SELECT order_date 
FROM fact_sales;

SELECT 
	MIN(order_date) AS first_order_date,
	MAX(order_date) AS last_order_date,
	YEAR(MAX(order_date)) -  YEAR(MIN(order_date))  AS order_range_years
FROM fact_sales;

-- Finding youngest and oldest customer
SELECT 
	MIN(birthdate) AS oldest_birthdate,
	MAX(birthdate) AS youngest_birthdate
FROM dim_customers;

SELECT 
    TIMESTAMPDIFF(YEAR, MIN(birthdate), CURRENT_DATE()) AS oldest_customer_age,
    TIMESTAMPDIFF(YEAR, MAX(birthdate), CURRENT_DATE()) AS youngest_customer_age
FROM dim_customers;

